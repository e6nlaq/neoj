import {
    collectValueOptions,
    commandCandidates,
    commandPathKeys,
    flattenCommands,
    type CompletionModel,
} from "@/lib/util/completion";

function renderPathResolution(model: CompletionModel): string {
    const groups = flattenCommands(model)
        .filter((entry) => entry.command.commands.length > 0)
        .flatMap((entry) =>
            commandPathKeys(entry).map((key) => ({
                key,
                children: entry.command.commands.flatMap((child) => [child.name, ...child.aliases]),
                nested: entry.path.length > 0,
            })),
        );

    return groups
        .map(
            ({ key, children, nested }) =>
                `            "${key}") case "$word" in ${children.join("|")}) path="${nested ? "$path " : ""}$word" ;; esac ;;`,
        )
        .join("\n");
}

function renderCommandCandidates(model: CompletionModel): string {
    const cases: string[] = [];
    for (const entry of flattenCommands(model)) {
        const values = commandCandidates(entry.command).map((candidate) => candidate.value);
        if (values.length === 0) {
            continue;
        }

        for (const key of commandPathKeys(entry)) {
            cases.push(
                `        "${key}")\n            COMPREPLY=( $(compgen -W "${values.join(" ")}" -- "$cur") )\n            ;;`,
            );
        }
    }

    return cases.join("\n");
}

function renderOptionValues(model: CompletionModel): string {
    const blocks: string[] = [];
    for (const option of collectValueOptions(model)) {
        const values = option.valueCandidates.map((candidate) => candidate.value).join(" ");
        const assignment = `COMPREPLY=( $(compgen -W "${values}" -- "$cur") )`;

        if (option.variadic) {
            blocks.push(
                `        ${option.flags.join("|")})\n            ${assignment}\n            return 0\n            ;;`,
            );
            continue;
        }

        const checks = option.flags.map((flag) => `[ "$prev" = "${flag}" ]`).join(" || ");
        blocks.push(
            `        ${option.flags.join("|")})\n            if ${checks}; then\n                ${assignment}\n                return 0\n            fi\n            ;;`,
        );
    }

    return blocks.join("\n");
}

export function renderBashCompletion(model: CompletionModel): string {
    return `# bash completion for ${model.name} (generated by "${model.name} completions bash")
_${model.name}_completion() {
    local cur prev i word path last_opt
    COMPREPLY=()
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"

    path=""
    for ((i = 1; i < COMP_CWORD; i++)); do
        word="\${COMP_WORDS[i]}"
        case "$word" in
            -*) continue ;;
        esac
        case "$path" in
${renderPathResolution(model)}
        esac
    done

    last_opt=""
    for ((i = COMP_CWORD - 1; i >= 1; i--)); do
        case "\${COMP_WORDS[i]}" in
            -*) last_opt="\${COMP_WORDS[i]}"; break ;;
        esac
    done

    case "$last_opt" in
${renderOptionValues(model)}
    esac

    case "$path" in
${renderCommandCandidates(model)}
    esac
}

complete -F _${model.name}_completion ${model.name}
`;
}

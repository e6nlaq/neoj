import {
    commandPathKey,
    flattenCommands,
    type CompletionCommand,
    type CompletionModel,
    type CompletionOption,
} from "@/lib/util/completion";

function fishQuote(value: string): string {
    return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

function combine(...conditions: (string | undefined)[]): string | undefined {
    const parts = conditions.filter((condition): condition is string => Boolean(condition));
    return parts.length === 0 ? undefined : parts.join("; and ");
}

function namesByPath(model: CompletionModel): Map<string, string[]> {
    const names = new Map<string, string[]>();
    for (const entry of flattenCommands(model)) {
        names.set(commandPathKey(entry.path), [entry.command.name, ...entry.command.aliases]);
    }
    return names;
}

function seenCondition(
    path: readonly string[],
    names: ReadonlyMap<string, string[]>,
): string | undefined {
    const parts = path.map((name, index) => {
        const key = commandPathKey(path.slice(0, index + 1));
        const candidates = names.get(key) ?? [name];
        return `__fish_seen_subcommand_from ${candidates.join(" ")}`;
    });

    return combine(...parts);
}

function completeLine(name: string, condition: string | undefined, arguments_: string): string {
    const conditionFlag = condition === undefined ? "" : ` -n ${fishQuote(condition)}`;
    return `complete -c ${name}${conditionFlag} ${arguments_}`;
}

function renderCommandCandidates(
    name: string,
    command: CompletionCommand,
    condition: string | undefined,
): string[] {
    if (command.commands.length === 0) {
        return [];
    }

    const names = command.commands.flatMap((child) => [child.name, ...child.aliases]);
    const childCondition = combine(condition, `not __fish_seen_subcommand_from ${names.join(" ")}`);

    return command.commands.flatMap((child) =>
        [child.name, ...child.aliases].map((name) =>
            completeLine(
                name,
                childCondition,
                `-a ${fishQuote(name)} -d ${fishQuote(child.description)}`,
            ),
        ),
    );
}

function renderOption(
    name: string,
    option: CompletionOption,
    condition: string | undefined,
): string {
    const flags = option.flags.map((flag) =>
        flag.startsWith("--") ? `-l ${flag.slice(2)}` : `-s ${flag.replace(/^-/u, "")}`,
    );
    if (option.takesValue) {
        flags.push("-r");
    }

    return completeLine(name, condition, `${flags.join(" ")} -d ${fishQuote(option.description)}`);
}

function renderOptionValues(
    name: string,
    option: CompletionOption,
    condition: string | undefined,
): string[] {
    const valueCondition = option.variadic
        ? `(${option.flags.map((flag) => `__neoj_last_option_is ${flag}`).join("; or ")})`
        : `(${option.flags.map((flag) => `__neoj_prev_is ${flag}`).join("; or ")})`;
    const combined = combine(condition, valueCondition);

    return option.valueCandidates.map((candidate) =>
        completeLine(
            name,
            combined,
            `-a ${fishQuote(candidate.value)}${
                candidate.description === undefined ? "" : ` -d ${fishQuote(candidate.description)}`
            }`,
        ),
    );
}

function renderArguments(
    name: string,
    command: CompletionCommand,
    condition: string | undefined,
): string[] {
    return command.args.flatMap((argument) => {
        if (argument.candidates.length === 0) {
            return [];
        }

        const guard = argument.variadic
            ? undefined
            : `not __fish_seen_subcommand_from ${argument.candidates
                  .map((candidate) => candidate.value)
                  .join(" ")}`;
        const combined = combine(condition, guard);

        return argument.candidates.map((candidate) =>
            completeLine(
                name,
                combined,
                `-a ${fishQuote(candidate.value)}${
                    candidate.description === undefined
                        ? ""
                        : ` -d ${fishQuote(candidate.description)}`
                }`,
            ),
        );
    });
}

export function renderFishCompletion(model: CompletionModel): string {
    const names = namesByPath(model);
    const rootGuard =
        model.commands.length === 0
            ? undefined
            : `not __fish_seen_subcommand_from ${model.commands
                  .flatMap((command) => [command.name, ...command.aliases])
                  .join(" ")}`;
    const lines: string[] = [
        `# fish completion for ${model.name} (generated by "${model.name} completions fish")`,
        "",
        `function __neoj_last_option_is
    set -l tokens (commandline -opc)
    set -l last ""
    for token in $tokens
        if string match -q -- '-*' $token
            set last $token
        end
    end
    test "$last" = "$argv[1]"
end`,
        "",
        `function __neoj_prev_is
    set -l tokens (commandline -opc)
    test (count $tokens) -ge 2 -a "$tokens[-1]" = "$argv[1]"
end`,
        "",
        `complete -c ${model.name} -f`,
    ];

    for (const entry of flattenCommands(model)) {
        const isRoot = entry.path.length === 0;
        const condition = isRoot ? rootGuard : seenCondition(entry.path, names);
        lines.push(
            ...renderCommandCandidates(model.name, entry.command, isRoot ? undefined : condition),
            ...entry.command.options.map((option) => renderOption(model.name, option, condition)),
            ...renderArguments(model.name, entry.command, condition),
            ...entry.command.options.flatMap((option) =>
                renderOptionValues(model.name, option, condition),
            ),
        );
    }

    return `${lines.join("\n")}\n`;
}

import {
    collectValueOptions,
    commandCandidates,
    commandPathKeys,
    flattenCommands,
    type CompletionCandidate,
    type CompletionModel,
} from "@/lib/util/completion";

function psQuote(value: string): string {
    return `'${value.replaceAll("'", "''")}'`;
}

function psResult(candidate: CompletionCandidate): string {
    const description = candidate.description ?? candidate.value;
    return `[System.Management.Automation.CompletionResult]::new(${psQuote(candidate.value)}, ${psQuote(candidate.value)}, 'ParameterValue', ${psQuote(description)})`;
}

function psArray(values: readonly string[]): string {
    return `@(${values.map(psQuote).join(", ")})`;
}

function renderPathResolution(model: CompletionModel): string {
    const groups = flattenCommands(model)
        .filter((entry) => entry.command.commands.length > 0)
        .flatMap((entry) =>
            commandPathKeys(entry).map((key) => ({
                key,
                children: entry.command.commands.flatMap((child) => [child.name, ...child.aliases]),
                nested: entry.path.length > 0,
            })),
        );

    const blocks = groups.map(
        ({ key, children, nested }, index) =>
            `${index === 0 ? "        if" : "        } elseif"} ($path -in ${psArray([key])}) {
            if ($token -in ${psArray(children)}) { $path = ${nested ? '"$path $token"' : "$token"} }
`,
    );

    if (blocks.length === 0) {
        return "";
    }

    return `${blocks.join("")}        }`;
}

function renderBranches(model: CompletionModel): string {
    const branches: { condition: string; body: string }[] = [];

    for (const option of collectValueOptions(model)) {
        const condition = option.variadic
            ? `$lastOption -in ${psArray(option.flags)}`
            : `$lastOption -in ${psArray(option.flags)} -and $previous -in ${psArray(option.flags)}`;
        branches.push({
            condition,
            body: `$candidates = @(\n${option.valueCandidates
                .map((candidate) => `            ${psResult(candidate)}`)
                .join("\n")}\n        )`,
        });
    }

    for (const entry of flattenCommands(model)) {
        const candidates = commandCandidates(entry.command);
        if (candidates.length === 0) {
            continue;
        }

        for (const key of commandPathKeys(entry)) {
            branches.push({
                condition: `$path -in ${psArray([key])}`,
                body: `$candidates = @(\n${candidates
                    .map((candidate) => `            ${psResult(candidate)}`)
                    .join("\n")}\n        )`,
            });
        }
    }

    return branches
        .map(
            ({ condition, body }, index) =>
                `    ${index === 0 ? "if" : "elseif"} (${condition}) {\n        ${body}\n    }`,
        )
        .join("\n");
}

export function renderPowerShellCompletion(model: CompletionModel): string {
    return `# PowerShell completion for ${model.name} (generated by "${model.name} completions powershell")
# Requires PowerShell 7.2 or later for native command argument completers.

Register-ArgumentCompleter -Native -CommandName ${model.name} -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $word = if ($null -eq $wordToComplete) { '' } else { [string]$wordToComplete }
    $tokens = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.Extent.Text })
    if ($tokens.Count -gt 0 -and $tokens[-1] -eq $word) {
        $tokens = @($tokens | Select-Object -SkipLast 1)
    }

    $path = ''
    foreach ($token in $tokens) {
        if ($token.StartsWith('-')) { continue }
${renderPathResolution(model)}
    }

    $lastOption = $null
    for ($i = $tokens.Count - 1; $i -ge 0; $i--) {
        if ($tokens[$i].StartsWith('-')) { $lastOption = $tokens[$i]; break }
    }
    $previous = if ($tokens.Count -gt 0) { $tokens[-1] } else { '' }

    $candidates = @()
${renderBranches(model)}

    $candidates | Where-Object {
        $_.CompletionText.StartsWith($word, [System.StringComparison]::OrdinalIgnoreCase)
    }
}
`;
}

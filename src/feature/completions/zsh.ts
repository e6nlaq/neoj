import {
    collectValueOptions,
    commandCandidates,
    commandPathKeys,
    flattenCommands,
    type CompletionCandidate,
    type CompletionModel,
    type CompletionOption,
} from "@/lib/util/completion";

function zshQuote(value: string): string {
    return `'${value.replaceAll("'", "'\\''")}'`;
}

function zshCandidate(candidate: CompletionCandidate): string {
    if (candidate.description === undefined) {
        return zshQuote(candidate.value);
    }

    const description = candidate.description.replaceAll(":", "\\:");
    return zshQuote(`${candidate.value}:${description}`);
}

function zshFunctionName(flag: string): string {
    return flag.replace(/^-+/u, "").replaceAll(/[^A-Za-z0-9]/gu, "_");
}

function renderValueFunctions(options: readonly CompletionOption[]): string {
    return options
        .map(
            (option) => `_neoj_values_${zshFunctionName(option.flags[0] ?? "")}() {
    local -a candidates
    candidates=(
${option.valueCandidates.map((candidate) => `        ${zshCandidate(candidate)}`).join("\n")}
    )
    _describe -t ${zshFunctionName(option.flags[0] ?? "")} ${zshQuote(option.description)} candidates
}`,
        )
        .join("\n\n");
}

function renderOptionValues(options: readonly CompletionOption[]): string {
    const blocks: string[] = [];
    for (const option of options) {
        const call = `_neoj_values_${zshFunctionName(option.flags[0] ?? "")}`;
        if (option.variadic) {
            blocks.push(
                `        ${option.flags.join("|")})\n            ${call}\n            return\n            ;;`,
            );
            continue;
        }

        const checks = option.flags.map((flag) => `[[ "$prev" = "${flag}" ]]`).join(" || ");
        blocks.push(
            `        ${option.flags.join("|")})\n            if ${checks}; then\n                ${call}\n                return\n            fi\n            ;;`,
        );
    }

    return blocks.join("\n");
}

function renderPathResolution(model: CompletionModel): string {
    const groups = flattenCommands(model)
        .filter((entry) => entry.command.commands.length > 0)
        .flatMap((entry) =>
            commandPathKeys(entry).map((key) => ({
                key,
                children: entry.command.commands.flatMap((child) => [child.name, ...child.aliases]),
                nested: entry.path.length > 0,
            })),
        );

    return groups
        .map(
            ({ key, children, nested }) =>
                `            "${key}") case "$word" in ${children.join("|")}) path="${nested ? "$path " : ""}$word" ;; esac ;;`,
        )
        .join("\n");
}

function renderCommandCandidates(model: CompletionModel): string {
    const cases: string[] = [];
    for (const entry of flattenCommands(model)) {
        const candidates = commandCandidates(entry.command);
        if (candidates.length === 0) {
            continue;
        }

        const tag = entry.path.length === 0 ? "commands" : "arguments";
        const message = entry.path.length === 0 ? `${model.name} command` : entry.path.join(" ");
        for (const key of commandPathKeys(entry)) {
            cases.push(
                `        "${key}")\n            local -a candidates\n            candidates=(\n${candidates
                    .map((candidate) => `                ${zshCandidate(candidate)}`)
                    .join(
                        "\n",
                    )}\n            )\n            _describe -t ${tag} ${zshQuote(message)} candidates\n            ;;`,
            );
        }
    }

    return cases.join("\n");
}

export function renderZshCompletion(model: CompletionModel): string {
    const valueOptions = collectValueOptions(model);

    return `#compdef ${model.name}
# zsh completion for ${model.name} (generated by "${model.name} completions zsh")

${renderValueFunctions(valueOptions)}

_${model.name}() {
    local prev i word path last_opt
    prev="\${words[CURRENT-1]}"

    path=""
    for (( i = 2; i < CURRENT; i++ )); do
        word="\${words[i]}"
        case "$word" in
            -*) continue ;;
        esac
        case "$path" in
${renderPathResolution(model)}
        esac
    done

    last_opt=""
    for (( i = CURRENT - 1; i >= 2; i-- )); do
        case "\${words[i]}" in
            -*) last_opt="\${words[i]}"; break ;;
        esac
    done

    case "$last_opt" in
${renderOptionValues(valueOptions)}
    esac

    case "$path" in
${renderCommandCandidates(model)}
    esac
}

if [ "\${funcstack[1]}" = "_${model.name}" ]; then
    _${model.name} "$@"
else
    compdef _${model.name} ${model.name}
fi
`;
}
